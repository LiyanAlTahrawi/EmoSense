import type { AuthMode, Profile } from './auth';
import type { Conversation, ConversationMessages, SendMessageResult } from './conversation';

/* ---------- Raw FastAPI payloads (snake_case, as returned by the EmoSense API) ---------- */

export interface RawProfile {
  user_id: string;
  first_name: string | null;
  last_name: string | null;
  phone_number: string | null;
}

export interface RawConversation {
  id: string;
  user_id: string;
  title: string | null;
  created_at: string;
  updated_at: string | null;
}

export interface RawAnalysis {
  id: string;
  message_id: string;
  transcript?: string | null;
  predicted_emotion?: string | null;
  emotion_confidence?: number | null;
  emotion_probabilities?: Record<string, number> | null;
  model_name?: string | null;
  model_version?: string | null;
  created_at?: string | null;
}

export interface RawMessage {
  id: string;
  conversation_id: string;
  role: string;
  content: string | null;
  input_type: string;
  created_at: string;
  audio_path?: string | null;
  analysis?: RawAnalysis | RawAnalysis[] | null;
  message_analysis?: RawAnalysis | RawAnalysis[] | null;
}

export interface RawSendResponse {
  status: string;
  message: RawMessage;
  analysis?: RawAnalysis | null;
  /** Future contract: the persisted assistant reply generated by the backend (OpenAI). */
  assistant_message?: RawMessage | null;
}

export interface UploadOptions {
  onProgress?: (fraction: number) => void;
}

/**
 * Every data operation the UI needs. Implemented by the real FastAPI client
 * (services/emosenseApi.ts) and by an isolated preview implementation (services/demoApi.ts).
 */
export interface EmoSenseService {
  mode: AuthMode;
  getMe(): Promise<{userId: string;email: string | null;}>;
  getProfile(): Promise<Profile>;
  updateProfile(input: Partial<Omit<Profile, 'userId'>>): Promise<Profile>;
  deleteAccount(): Promise<void>; 
  listConversations(): Promise<Conversation[]>;
  createConversation(title: string): Promise<Conversation>;
  renameConversation(id: string, title: string): Promise<Conversation>;
  deleteConversation(id: string): Promise<void>;
  deleteAllConversations(): Promise<void>;
  listMessages(conversationId: string): Promise<ConversationMessages>;
  sendTextMessage(conversationId: string, content: string): Promise<SendMessageResult>;
  sendAudioMessage(conversationId: string, file: File, options?: UploadOptions): Promise<SendMessageResult>;
}